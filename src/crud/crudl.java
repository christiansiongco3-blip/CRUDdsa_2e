    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row = jTable2.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this,
            "Please select a player.");
        return;
    }

    String fullName = jTextField2.getText().trim();
    String ign = jTextField3.getText().trim();

    if (fullName.isEmpty() || ign.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Please enter Full Name and IGN.");
        return;
    }

    int playerNo = Integer.parseInt(
        model.getValueAt(row, 0).toString()
    );

    String sql = "UPDATE Table1 SET FullName = ?, IGN = ? WHERE PlayerNo = ?";

    try (Connection con = MsConnectAccess.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, fullName);
        pst.setString(2, ign);
        pst.setInt(3, playerNo);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
            "Player updated successfully!");

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");

        loadPlayers();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Database Error: " + e.getMessage());
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

